-- Collabor8 monitoring and alerting (test environment first).
-- Server-only config. Not readable by parents or anon.
CREATE TABLE IF NOT EXISTS public.sg_runtime_config (
  key text PRIMARY KEY,
  value text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.sg_runtime_config ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.sg_runtime_config FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.sg_runtime_config TO service_role;

-- One row per alert delivery attempt. Never stores message text or phone numbers.
CREATE TABLE IF NOT EXISTS public.sg_alert_deliveries (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  kind text NOT NULL,
  test_account boolean NOT NULL,
  channel text NOT NULL CHECK (channel IN ('email', 'sms')),
  recipient_role text NOT NULL CHECK (recipient_role IN ('qa', 'dsl', 'none')),
  recipient_domain text,
  subject_test_prefix boolean,
  status text NOT NULL CHECK (status IN ('sent', 'failed', 'dropped', 'skipped')),
  reason text
);
ALTER TABLE public.sg_alert_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.sg_alert_deliveries FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.sg_alert_deliveries TO service_role;
CREATE INDEX IF NOT EXISTS sg_alert_deliveries_created_idx ON public.sg_alert_deliveries (created_at DESC);

CREATE TABLE IF NOT EXISTS public.monitor_health_checks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  checked_at timestamptz NOT NULL DEFAULT now(),
  ok boolean NOT NULL,
  http_status integer,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb
);
ALTER TABLE public.monitor_health_checks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.monitor_health_checks FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.monitor_health_checks TO service_role;
CREATE INDEX IF NOT EXISTS monitor_health_checks_at_idx ON public.monitor_health_checks (checked_at DESC);

CREATE TABLE IF NOT EXISTS public.monitor_pending_requests (
  request_id bigint PRIMARY KEY,
  purpose text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.monitor_pending_requests ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.monitor_pending_requests FROM PUBLIC, anon, authenticated;

