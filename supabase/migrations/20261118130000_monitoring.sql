CREATE OR REPLACE FUNCTION public.monitor_config(_key text)
RETURNS text LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT value FROM public.sg_runtime_config WHERE key = _key
$$;
REVOKE ALL ON FUNCTION public.monitor_config(text) FROM PUBLIC, anon, authenticated;

-- Starts one HTTP health check of the edge runtime + database.
CREATE OR REPLACE FUNCTION public.monitor_start_health_check()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  base text := COALESCE(public.monitor_config('project_url'), '');
  rid bigint;
BEGIN
  -- Not configured yet (for example straight after this migration on a new project): do nothing, raise nothing.
  IF base = '' THEN
    RETURN;
  END IF;
  SELECT net.http_get(url := base || '/functions/v1/safeguarding-health', timeout_milliseconds := 10000) INTO rid;
  INSERT INTO public.monitor_pending_requests (request_id, purpose) VALUES (rid, 'health');
END;
$$;
REVOKE ALL ON FUNCTION public.monitor_start_health_check() FROM PUBLIC, anon, authenticated;

-- Reads finished health checks, records them, and raises a monitoring alert after 2 failures in a row.
CREATE OR REPLACE FUNCTION public.monitor_collect_health_checks()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  p record;
  r record;
  body jsonb;
  cron_failures integer;
  failed_in_row integer;
BEGIN
  SELECT count(*) INTO cron_failures
  FROM cron.job_run_details
  WHERE status = 'failed' AND start_time > now() - interval '15 minutes';

  FOR p IN SELECT * FROM public.monitor_pending_requests WHERE purpose = 'health' ORDER BY created_at LOOP
    SELECT * INTO r FROM net._http_response WHERE id = p.request_id;
    IF FOUND THEN
      BEGIN
        body := r.content::jsonb;
      EXCEPTION WHEN OTHERS THEN
        body := NULL;
      END;
      INSERT INTO public.monitor_health_checks (checked_at, ok, http_status, detail)
      VALUES (
        p.created_at,
        r.status_code = 200 AND COALESCE(body->>'ok', '') = 'true' AND cron_failures = 0,
        r.status_code,
        jsonb_build_object(
          'db', body->>'db',
          'edge', body->>'edge',
          'timed_out', COALESCE(r.timed_out, false),
          'error', left(COALESCE(r.error_msg, ''), 200),
          'cron_failures_15m', cron_failures
        )
      );
      DELETE FROM public.monitor_pending_requests WHERE request_id = p.request_id;
    ELSIF p.created_at < now() - interval '3 minutes' THEN
      INSERT INTO public.monitor_health_checks (checked_at, ok, detail)
      VALUES (p.created_at, false, jsonb_build_object('reason', 'no_response', 'cron_failures_15m', cron_failures));
      DELETE FROM public.monitor_pending_requests WHERE request_id = p.request_id;
    END IF;
  END LOOP;

  SELECT count(*) INTO failed_in_row FROM (
    SELECT ok FROM public.monitor_health_checks ORDER BY checked_at DESC LIMIT 2
  ) last2 WHERE NOT ok;
  IF failed_in_row = 2 AND public.sg_claim_monitor_alert() THEN
    PERFORM public.dispatch_safeguarding_alert(NULL, NULL, 'monitoring');
  END IF;

  DELETE FROM public.monitor_health_checks WHERE checked_at < now() - interval '30 days';
END;
$$;
REVOKE ALL ON FUNCTION public.monitor_collect_health_checks() FROM PUBLIC, anon, authenticated;

-- Keep-alive: one REST API request so a Free project is not paused for inactivity.
CREATE OR REPLACE FUNCTION public.monitor_keep_alive()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  base text := COALESCE(public.monitor_config('project_url'), '');
  anon text := COALESCE(public.monitor_config('anon_key'), '');
BEGIN
  IF base = '' OR anon = '' THEN RETURN; END IF;
  PERFORM net.http_get(
    url := base || '/rest/v1/app_settings?select=key&limit=1',
    headers := jsonb_build_object('apikey', anon, 'Authorization', 'Bearer ' || anon)
  );
END;
$$;
REVOKE ALL ON FUNCTION public.monitor_keep_alive() FROM PUBLIC, anon, authenticated;

-- Admin-only summary for /admin/monitoring.
CREATE OR REPLACE FUNCTION public.admin_monitoring_summary()
RETURNS jsonb LANGUAGE plpgsql STABLE SECURITY DEFINER SET search_path = public AS $$
DECLARE
  out jsonb;
BEGIN
  IF auth.uid() IS NULL OR NOT (public.is_admin(auth.uid()) OR public.has_role(auth.uid(), 'admin')) THEN
    RAISE EXCEPTION 'not allowed' USING ERRCODE = '42501';
  END IF;
  SELECT jsonb_build_object(
    'generated_at', now(),
    'environment', COALESCE(public.monitor_config('environment'), 'live'),
    'last_health_check', (
      SELECT jsonb_build_object('checked_at', checked_at, 'ok', ok, 'http_status', http_status, 'detail', detail)
      FROM public.monitor_health_checks ORDER BY checked_at DESC LIMIT 1),
    'health_24h', (
      SELECT jsonb_build_object('total', count(*), 'failed', count(*) FILTER (WHERE NOT ok))
      FROM public.monitor_health_checks WHERE checked_at > now() - interval '24 hours'),
    'alert_deliveries_7d', (
      SELECT jsonb_build_object(
        'sent_test', count(*) FILTER (WHERE status = 'sent' AND test_account),
        'sent_real', count(*) FILTER (WHERE status = 'sent' AND NOT test_account),
        'failed_test', count(*) FILTER (WHERE status IN ('failed', 'dropped') AND test_account),
        'failed_real', count(*) FILTER (WHERE status IN ('failed', 'dropped') AND NOT test_account),
        'skipped', count(*) FILTER (WHERE status = 'skipped'))
      FROM public.sg_alert_deliveries WHERE created_at > now() - interval '7 days'),
    'recent_deliveries', (
      SELECT COALESCE(jsonb_agg(d ORDER BY d.created_at DESC), '[]'::jsonb) FROM (
        SELECT created_at, kind, test_account, channel, recipient_role, subject_test_prefix, status, reason
        FROM public.sg_alert_deliveries ORDER BY created_at DESC LIMIT 10) d),
    'alerts_not_dispatched_7d', (
      SELECT count(*) FROM public.safeguarding_audit_log
      WHERE action = 'alert_skipped' AND created_at > now() - interval '7 days'),
    'concerns', (
      SELECT jsonb_build_object('total', count(*), 'last_7d', count(*) FILTER (WHERE created_at > now() - interval '7 days'))
      FROM public.safeguarding_concerns),
    'paused_families', (SELECT count(*) FROM public.family_safeguarding WHERE paused_at IS NOT NULL),
    'safeguarding_global_on', public.sg_global_enabled(),
    'scheduled_jobs_24h', (
      SELECT jsonb_build_object('runs', count(*), 'failed', count(*) FILTER (WHERE status = 'failed'))
      FROM cron.job_run_details WHERE start_time > now() - interval '24 hours'),
    'edge_calls_from_db_6h', (
      SELECT jsonb_build_object('total', count(*), 'errors', count(*) FILTER (WHERE status_code IS NULL OR status_code >= 400))
      FROM net._http_response WHERE created > now() - interval '6 hours'),
    'last_backup', (
      SELECT jsonb_build_object('backup_at', backup_at, 'source', source)
      FROM public.monitor_backups ORDER BY backup_at DESC LIMIT 1)
  ) INTO out;
  RETURN out;
END;
$$;
REVOKE ALL ON FUNCTION public.admin_monitoring_summary() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_monitoring_summary() TO authenticated;

