-- Collabor8 uptime alerting: state, history and a 5-minute check.
-- NOT APPLIED. Needs Rafa's own yes before it runs on any project.
-- Rollback: NEEDS_RAFA_APPROVAL_service_uptime_alerts_ROLLBACK.sql
--
-- Every 5 minutes pg_cron calls the admin-system-health edge function with a
-- random key that only lives in sg_runtime_config (service role only). The function
-- runs the checks, keeps one state row per service, and emails "Service down" once
-- after two failed checks in a row, then "Service recovered" once when it is back.
-- Rows hold service names, statuses, HTTP status codes, response times and times only.

CREATE TABLE IF NOT EXISTS public.monitor_service_status (
  service text PRIMARY KEY,
  label text NOT NULL,
  state text NOT NULL DEFAULT 'up' CHECK (state IN ('up', 'down')),
  down_since timestamptz,
  last_status text NOT NULL CHECK (last_status IN ('up', 'problem', 'down', 'not_configured')),
  last_checked_at timestamptz NOT NULL DEFAULT now(),
  last_response_ms integer,
  last_http_status integer,
  consecutive_failures integer NOT NULL DEFAULT 0,
  first_failed_at timestamptz
);
ALTER TABLE public.monitor_service_status ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.monitor_service_status FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.monitor_service_status TO service_role;

CREATE TABLE IF NOT EXISTS public.monitor_service_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at timestamptz NOT NULL DEFAULT now(),
  service text NOT NULL,
  service_label text NOT NULL,
  event text NOT NULL CHECK (event IN ('down', 'recovered')),
  http_status integer,
  response_ms integer,
  down_since timestamptz,
  problem text CHECK (problem IS NULL OR length(problem) <= 120),
  email_status text CHECK (email_status IS NULL OR email_status IN ('sent', 'partly_sent', 'failed', 'dropped'))
);
ALTER TABLE public.monitor_service_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.monitor_service_events FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.monitor_service_events TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.monitor_service_events_id_seq TO service_role;
CREATE INDEX IF NOT EXISTS monitor_service_events_at_idx ON public.monitor_service_events (occurred_at DESC);

-- Random key for the cron call. Never leaves the database and the edge function.
INSERT INTO public.sg_runtime_config (key, value)
VALUES ('monitor_cron_key', encode(extensions.gen_random_bytes(32), 'hex'))
ON CONFLICT (key) DO NOTHING;

CREATE OR REPLACE FUNCTION public.monitor_start_service_checks()
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  base text := COALESCE(public.monitor_config('project_url'), '');
  k text := COALESCE(public.monitor_config('monitor_cron_key'), '');
BEGIN
  IF base = '' OR k = '' THEN
    RETURN;
  END IF;
  PERFORM net.http_post(
    url := base || '/functions/v1/admin-system-health',
    headers := jsonb_build_object('Content-Type', 'application/json', 'x-monitor-key', k),
    body := '{"mode":"cron"}'::jsonb,
    timeout_milliseconds := 30000
  );
  DELETE FROM public.monitor_service_events WHERE occurred_at < now() - interval '180 days';
END;
$$;
REVOKE ALL ON FUNCTION public.monitor_start_service_checks() FROM PUBLIC, anon, authenticated;

SELECT cron.unschedule(jobname) FROM cron.job WHERE jobname = 'c8-service-health';
SELECT cron.schedule('c8-service-health', '*/5 * * * *', $cron$ SELECT public.monitor_start_service_checks(); $cron$);
