CREATE OR REPLACE FUNCTION public.has_premium_access(uid uuid)
RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT EXISTS (
    SELECT 1 FROM public.conversation_tool_access c
    WHERE c.user_id = uid
      AND (c.subscription_status IN ('active','trialing')
           OR (c.expires_at IS NOT NULL AND c.expires_at > now())
           OR (c.current_period_end IS NOT NULL AND c.current_period_end > now()))
  ) OR EXISTS (
    SELECT 1 FROM public.store_subscriptions s
    WHERE s.user_id = uid AND s.status = 'active' AND (s.expires_at IS NULL OR s.expires_at > now())
  )
$$;

CREATE OR REPLACE FUNCTION public.admin_signup_classification()
RETURNS TABLE (user_id uuid, created_at timestamptz, created_day_uk date, week_start_uk date, email_confirmed boolean, exclusion_reason text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT u.id, u.created_at,
    (u.created_at AT TIME ZONE 'Europe/London')::date,
    date_trunc('week', u.created_at AT TIME ZONE 'Europe/London')::date,
    u.email_confirmed_at IS NOT NULL,
    COALESCE(
      (SELECT e.reason FROM public.admin_signup_exclusions e
        WHERE (e.kind = 'email' AND lower(e.value) = lower(u.email))
           OR (e.kind = 'domain' AND lower(split_part(u.email,'@',2)) = lower(e.value))
           OR (e.kind = 'user_id' AND e.value = u.id::text) LIMIT 1),
      CASE WHEN p.is_test_account THEN 'test_account' END)
  FROM auth.users u LEFT JOIN public.profiles p ON p.id = u.id
  WHERE auth.role() = 'service_role' OR public.is_admin(auth.uid())
$$;

CREATE OR REPLACE FUNCTION public.admin_real_signups(_from timestamptz, _to timestamptz DEFAULT now())
RETURNS TABLE (real_parent_signups bigint, confirmed bigint)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT count(*), count(*) FILTER (WHERE email_confirmed)
  FROM public.admin_signup_classification()
  WHERE exclusion_reason IS NULL AND created_at >= _from AND created_at < _to
$$;

CREATE OR REPLACE FUNCTION public.admin_signup_summary(_weeks integer DEFAULT 8)
RETURNS jsonb LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public AS $$
  SELECT jsonb_build_object(
    'weeks', COALESCE(jsonb_agg(jsonb_build_object('week_start', w, 'signups', n, 'confirmed', c) ORDER BY w), '[]'::jsonb),
    'total_real', (SELECT count(*) FROM public.admin_signup_classification() WHERE exclusion_reason IS NULL))
  FROM (
    SELECT week_start_uk w, count(*) n, count(*) FILTER (WHERE email_confirmed) c
    FROM public.admin_signup_classification()
    WHERE exclusion_reason IS NULL AND week_start_uk >= (now() - make_interval(weeks => _weeks))::date
    GROUP BY 1) s
$$;

